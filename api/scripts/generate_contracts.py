"""Generate TS types + runtime schemas without a generator dependency.

Run from api: python scripts/generate_contracts.py [--check]
"""
import inspect
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app import schemas
from app.persistence import models as memory_models
from app.discovery import models as discovery_models
from app.menu_sources import models as menu_source_models
from app.real_picks import models as real_picks_models
from app.menu_extraction import models as extraction_models, vision as vision_models


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(value) for value in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind == "object":
        return "{\n" + "".join(f"  {key}{'' if key in schema.get('required', []) else '?'}: {ts_type(value)};\n" for key, value in schema.get("properties", {}).items()) + "}"
    return {"integer": "number", "number": "number", "boolean": "boolean", "string": "string", "null": "null"}.get(kind, "unknown")


def generate() -> dict[Path, str]:
    definitions = {}
    for name, value in {**vars(schemas), **vars(memory_models), **vars(discovery_models), **vars(menu_source_models), **vars(extraction_models), **vars(vision_models), **vars(real_picks_models)}.items():
        if inspect.isclass(value) and issubclass(value, schemas.Contract) and value is not schemas.Contract:
            schema = value.model_json_schema(mode="serialization")
            definitions.update(schema.pop("$defs", {}))
            definitions[name] = schema
    # API responses include all fields, including server-filled defaults.
    for schema in definitions.values():
        if schema.get("type") == "object":
            schema["required"] = [key for key, field in schema.get("properties", {}).items() if not field.get("x-response-optional", False)]
    header = "// Generated by api/scripts/generate_contracts.py. Do not edit by hand.\n\n"
    types = header + "\n\n".join(f"export type {name} = {ts_type(schema)};" for name, schema in sorted(definitions.items())) + "\n"
    target = Path(__file__).resolve().parents[2] / "web" / "lib" / "generated"
    return {target / "contracts.ts": types, target / "contracts.schema.json": json.dumps({"$defs": definitions}, indent=2, ensure_ascii=False) + "\n"}


if __name__ == "__main__":
    for path, content in generate().items():
        if "--check" in sys.argv:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Contract drift: regenerate {path.name}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print("Contracts are current." if "--check" in sys.argv else "Generated frontend contracts and runtime validation schemas.")
